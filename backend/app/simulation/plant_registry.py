def get_plant_profile(plant_id: str) -> Optional[Dict[str, Any]]:
    """Retrieves agronomic profile for a specific plant or crop."""
    key = plant_id.lower().strip().replace(" ", "_")
    return PLANT_REGISTRY.get(key)


def get_all_plants() -> List[Dict[str, Any]]:
    """Retrieves all registered plants and trees."""
    return list(PLANT_REGISTRY.values())


def format_plant_database_for_prompt() -> str:
    """
    Serializes the complete plant agronomic knowledge base into an optimized,
    dense markdown encyclopedia for injection into the Qwen 3.5 / LLM system prompt.
    """
    lines = [
        "=== AGRONOMIC PLANTS & CROPS KNOWLEDGE BASE ===",
        "You have complete access to the following certified agronomic profiles for all plants and trees in the digital twin:\n",
    ]

    for p in PLANT_REGISTRY.values():
        var_str = ", ".join(p["varieties"][:3])
        npk = p["optimal_npk_ppm"]
        lines.append(
            f"• **{p['name']}** (`{p['id']}` - {p['scientific_name']}):\n"
            f"  - Category: {p['category']} | Varieties: {var_str}\n"
            f"  - Thermal: Base Temp={p['base_temp_c']}°C, GDD to Maturity={p['gdd_maturity']} GDD ({p['growing_season_days']})\n"
            f"  - Water & Moisture: Kc=[ini:{p['kc_stages']['initial']}, mid:{p['kc_stages']['mid']}, end:{p['kc_stages']['end']}], Daily Water={p['water_demand_mm_per_day']}, Optimal Moisture={p['optimal_soil_moisture_pct']}\n"
            f"  - Soil & Nutrition: pH={p['optimal_ph']}, N={npk['n']}ppm, P={npk['p']}ppm, K={npk['k']}ppm\n"
            f"  - Root & Yield: Root Depth={p['root_depth_cm']}, Max Yield={p['max_yield_kg_per_m2']} kg/m²\n"
            f"  - Agronomic Guidance: {p['tolerance']} {p['management_tips']}"
        )

    lines.append("\nUse this exact agronomic data whenever diagnosing crops, prescribing irrigation rates, recommending varieties, or calculating GDD and yield projections.")
    return "\n".join(lines)
